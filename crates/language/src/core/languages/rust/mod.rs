impl TryFrom<()> for Rust {
    type Error = Error;

    fn try_from(_: ()) -> Result<Self, Self::Error> {
        let words = Self::WORDS.iter().copied();
        let language = Language::default().try_admit(words)?;
        Ok(Self { language })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_words_of_rust_are_read() {
        let rust = Rust::try_from(());

        let fit = rust.is_ok();

        assert!(fit);
    }

    #[test]
    fn a_keyword_of_rust_is_not_refused() {
        let rust = Rust::try_from(()).unwrap();

        let unknown_vocabulary = rust.language().unknown_vocabulary("struct");

        assert!(unknown_vocabulary.is_empty());
    }

    #[test]
    fn a_word_of_the_domain_is_refused_by_rust_alone() {
        let rust = Rust::try_from(()).unwrap();

        let unknown_vocabulary = rust.language().unknown_vocabulary("treasure");

        assert!(!unknown_vocabulary.is_empty());
    }

    #[test]
    fn the_words_of_rust_are_the_same_every_time() {
        let first_error = Rust::try_from(()).unwrap();
        let second_error = Rust::try_from(()).unwrap();

        assert_eq!(first_error, second_error);
    }
}
